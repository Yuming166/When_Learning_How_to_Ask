"""Deterministic accounting fixtures: no simulated worlds, private files or models."""
from copy import deepcopy
import json
from pathlib import Path
import sys
from tempfile import TemporaryDirectory
import unittest

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import numpy as np

from t1.analyze import (BOOTSTRAP_RESAMPLES, BOOTSTRAP_SEED, METHODS, OFFLINE_METHODS,
                        POSITIONS, analyze_records, plots, write_reports)
from t1.data import world_plan, evaluation_world_plan


def fixture():
    """Every score here is hand assigned, never generated by an environment."""
    data_plan, evaluation_plan = world_plan({}), evaluation_world_plan({})
    manifest = {"status": "completed", "wall_seconds": 2.,
                "generated_online_actions": 96 * 1928, "unique_generated_offline_observations": 100,
                "worlds": [{"world_id": r["world_id"], "split": r["split"], "row_count": 16} for r in data_plan],
                "splits": {split: {"worlds": count, "states": count * 16} for split, count in
                           (("train", 64), ("validation", 8), ("id_test", 8), ("ood_parameters", 8), ("ood_partition", 8))}}
    records = []
    for method_index, method in enumerate(OFFLINE_METHODS):
        for split in ("id_test", "ood_parameters", "ood_partition"):
            worlds = sorted(r["world_id"] for r in data_plan if r["split"] == split)
            for i, world in enumerate(worlds):
                for position in POSITIONS:
                    # Base-LoRA is -(i+1)/100; repeated states are deliberately correlated.
                    value = (method_index + 1) * (i + 1) / 100 + position / 1000
                    records.append({"method": method, "world_id": world, "split": split,
                                    "row_id": f"{world}:{position}", "state": {"online": 8 + 128 * position},
                                    "fallback": False, "valid": True,
                                    "allocation_l1": value, "forward_kl_epsilon_1e8": value / 2,
                                    "plugin_relative_information_deficit": value - .2,
                                    "percent_l1": .02, "percent_exact": False,
                                    "teacher_rounding_l1": .01, "student_rounding_l1": 0.,
                                    "inference_wall_seconds": .002 * (method_index + 1),
                                    "inference_cpu_seconds": .001, "prompt_tokens": 100, "output_tokens": 10})
    paths = []
    diagnostic_ids = {next(r["world_id"] for r in evaluation_plan if r["split"] == split)
                      for split in ("eval_id", "eval_ood_parameters", "eval_ood_partition")}
    for spec_index, spec in enumerate(evaluation_plan):
        for method_index, method in enumerate(METHODS):
            for diagnostic in (False, True) if spec["world_id"] in diagnostic_ids else (False,):
                certified = diagnostic and method == "LoRA"
                online = 256 if certified else 2048 if diagnostic else 512
                offline = 2 * spec["M"]
                predictions = [{"online": t, "inference_wall_seconds": .01} for t in range(8, online, 128)]
                candidate = [0, 1, 0, 1]
                certificate = {"certified": True, "interval_certified": True, "status": "certified",
                               "decision": "stop", "candidate_theta": candidate, "theta": candidate,
                               "gap_lower": "2.0000000000000000001", "beta_upper": "2"} if certified else None

                def snapshot(t):
                    type_count = 0 if method == "DNoTypeBlock128" else 8
                    costs = {"task": t - type_count, "type": type_count, "offline": offline}
                    return {"online": t, "costs": costs, "total_acquisition": t + offline,
                            "guess": candidate, "strict_certificate": certificate,
                            "strictly_certified_output": candidate if certified else None,
                            "guess_exact": bool((spec_index + method_index + (t == 512)) % 3),
                            "inference_wall_seconds": .01 * sum(p["online"] < t for p in predictions),
                            "inference_cpu_seconds": .001, "elapsed_wall_seconds": 1.,
                            "elapsed_cpu_seconds": .5, "prompt_tokens": 200,
                            "output_tokens": 20, "invalid_fallbacks": 0}
                final = snapshot(online)
                paths.append({"world_id": spec["world_id"], "split": spec["split"], "method": method,
                              "mode": "fixed_confidence_diagnostic" if diagnostic else "fixed_budget",
                              "status": "completed", "error": None, "R": 16 if diagnostic else 64,
                              "public_online_cap": 2048, "online": online, "costs": final["costs"],
                              "total_acquisition": final["total_acquisition"], "complete": certified,
                              "abstained": diagnostic and not certified,
                              "strictly_certified_output": candidate if certified else None,
                              "gate_history": [{"online": online, **certificate}] if certified else [],
                              "certified_exact": (spec_index != 0) if certified else None,
                              "snapshots": [snapshot(online)] if diagnostic else [snapshot(256), snapshot(512)],
                              "predictions": predictions, "inference_calls": len(predictions),
                              "inference_wall_seconds": .01 * len(predictions), "inference_cpu_seconds": .02,
                              "prompt_tokens": 100 * len(predictions), "output_tokens": 10 * len(predictions),
                              "invalid_fallbacks": 0, "wall_seconds": 2., "cpu_seconds": 1.,
                              "glr_wall_seconds": .1, "glr_cpu_seconds": .08,
                              "gate_wall_seconds": .2 if diagnostic else 0., "gate_cpu_seconds": .18 if diagnostic else 0.})
    qwen_calls = sum(r["method"] in ("BaseQwen", "LoRA") for r in records) + sum(
        r["inference_calls"] for r in paths if r["method"] in ("BaseQwen", "LoRA"))
    receipts = {"training": {"status": "completed", "wall_seconds": 10., "load_seconds": 3.,
                             "process_cpu_seconds": 4., "optimizer_steps": 128, "train_target_tokens": 1000,
                             "validation_tokens": 100, "peak_allocated_bytes": 2000},
                "mlp": {"status": "completed", "training_wall_seconds": 1., "training_cpu_seconds": 1., "optimizer_updates": 200},
                "evaluation": {"status": "completed", "wall_seconds": 20., "process_cpu_seconds": 15.,
                               "resident_model": {"load_seconds": 5.}, "peak_allocated_bytes": 3000,
                               "policy_calls": {"calls": qwen_calls}}}
    summaries = [{"method": method, "states": 120, "recorded_states": 120} for method in OFFLINE_METHODS]
    return [{}, manifest, records, paths, receipts, summaries]


class AnalysisTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.raw = fixture()
        cls.complete = analyze_records(*cls.raw)

    def test_exact_requested_coverage_and_world_units(self):
        result = self.complete
        self.assertEqual(result["coverage"]["status"], "COMPLETE")
        self.assertEqual(result["coverage"]["offline"]["requested"], 360)
        self.assertEqual(result["coverage"]["paths"]["requested"], 189)
        self.assertEqual(len(result["offline_worlds"]), 72)
        self.assertEqual(len(result["primary_summary"]), 56)
        self.assertEqual(sum(r["observed_readouts"] for r in result["primary_summary"] if r["split"] != "all_24_worlds"), 336)
        for row in result["offline_summary"]:
            count = 24 if row["split"] == "all_24_worlds" else 8
            self.assertEqual(row["metrics"]["allocation_l1"]["requested"], count)
            self.assertEqual(row["requested_states"], count * 5)
        self.assertIn("saved teacher_percent", result["analysis_protocol"]["percent_targets"])

    def test_five_states_average_before_world_bootstrap(self):
        pair = next(r for r in self.complete["offline_paired"] if r["split"] == "id_test"
                    and r["left"] == "BaseQwen" and r["right"] == "LoRA" and r["metric"] == "allocation_l1")
        expected = -np.arange(1, 9) / 100
        np.testing.assert_allclose(pair["paired_vector"], expected)
        self.assertEqual(pair["requested_pairs"], 8)
        draws = np.random.default_rng(BOOTSTRAP_SEED).integers(0, 8, (BOOTSTRAP_RESAMPLES, 8))
        np.testing.assert_allclose(pair["bootstrap_95"], np.quantile(expected[draws].mean(axis=1), [.025, .975]))
        self.assertAlmostEqual(pair["mean_difference"], -.045)
        world = next(r for r in self.complete["offline_worlds"] if r["world_id"] == pair["world_ids"][0] and r["method"] == "BaseQwen")
        self.assertAlmostEqual(world["metrics"]["allocation_l1"]["mean"], .02 + np.mean(POSITIONS) / 1000)

    def test_pooled_24_world_display_reuses_same_worlds(self):
        pooled = next(r for r in self.complete["primary_summary"] if r["split"] == "all_24_worlds"
                      and r["method"] == "LoRA" and r["budget"] == 512)
        parts = [r for r in self.complete["primary_summary"] if r["split"] != "all_24_worlds"
                 and r["method"] == "LoRA" and r["budget"] == 512]
        self.assertEqual(pooled["requested_worlds"], 24)
        self.assertEqual(pooled["exact_recovered"], sum(r["exact_recovered"] for r in parts))
        pair = next(r for r in self.complete["offline_paired"] if r["split"] == "all_24_worlds"
                    and r["left"] == "BaseQwen" and r["right"] == "LoRA" and r["metric"] == "allocation_l1")
        self.assertEqual(len(set(pair["world_ids"])), 24)
        self.assertEqual(pair["requested_pairs"], 24)

    def test_missing_offline_state_never_becomes_four_state_mean(self):
        raw = deepcopy(self.raw)
        removed = next(r for r in raw[2] if r["method"] == "LoRA" and r["split"] == "id_test")
        raw[2].remove(removed)
        next(r for r in raw[5] if r["method"] == "LoRA")["recorded_states"] -= 1
        result = analyze_records(*raw)
        self.assertEqual(result["coverage"]["status"], "INCOMPLETE")
        world = next(r for r in result["offline_worlds"] if r["world_id"] == removed["world_id"] and r["method"] == "LoRA")
        self.assertEqual(world["observed_states"], 4)
        self.assertIsNone(world["metrics"]["allocation_l1"]["mean"])
        pair = next(r for r in result["offline_paired"] if r["split"] == "id_test" and r["left"] == "BaseQwen"
                    and r["right"] == "LoRA" and r["metric"] == "allocation_l1")
        self.assertEqual(pair["observed_pairs"], 7)
        self.assertIsNone(pair["mean_difference"])
        self.assertIsNone(pair["bootstrap_95"])

    def test_missing_readout_retains_full_denominator_and_bounds(self):
        raw = deepcopy(self.raw)
        path = next(r for r in raw[3] if r["method"] == "LoRA" and r["split"] == "eval_id" and r["mode"] == "fixed_budget")
        path["status"] = "failed"
        path["snapshots"] = path["snapshots"][:1]
        result = analyze_records(*raw)
        self.assertEqual(result["coverage"]["status"], "INCOMPLETE")
        row = next(r for r in result["primary_summary"] if r["method"] == "LoRA" and r["split"] == "eval_id" and r["budget"] == 512)
        self.assertEqual((row["requested_worlds"], row["observed_readouts"], row["failed_paths"]), (8, 7, 1))
        self.assertIsNone(row["exact_recovery"])
        self.assertAlmostEqual(row["recovery_identification_bounds"][1] - row["recovery_identification_bounds"][0], 1 / 8)
        pair = next(r for r in result["primary_paired"] if r["split"] == "eval_id" and r["budget"] == 512
                    and r["left"] == "LoRA" and r["right"] == "BaseQwen")
        self.assertEqual(pair["missing_pairs"], 1)
        self.assertIsNone(pair["bootstrap_95"])

    def test_invalid_fallback_is_retained_and_negative_deficit_not_clamped(self):
        raw = deepcopy(self.raw)
        row = raw[2][0]
        row.update(valid=False, fallback=True)
        result = analyze_records(*raw)
        summary = next(r for r in result["offline_summary"] if r["method"] == row["method"] and r["split"] == row["split"])
        self.assertEqual(summary["invalid_fallbacks"], 1)
        self.assertEqual(summary["observed_states"], 40)
        self.assertEqual(summary["metrics"]["allocation_l1"]["observed"], 8)
        self.assertLess(summary["metrics"]["plugin_relative_information_deficit"]["mean"], 0.)

    def test_duplicate_or_unexpected_records_fail_closed(self):
        for kind in ("duplicate_offline", "duplicate_path", "unplanned_position", "unplanned_world"):
            raw = deepcopy(self.raw)
            if kind == "duplicate_offline":
                raw[2].append(deepcopy(raw[2][0]))
            elif kind == "duplicate_path":
                raw[3].append(deepcopy(raw[3][0]))
            elif kind == "unplanned_position":
                raw[2][0]["row_id"] = raw[2][0]["world_id"] + ":1"
                raw[2][0]["state"]["online"] = 136
            else:
                raw[3][0]["world_id"] = "unplanned"
            with self.subTest(kind=kind), self.assertRaises(ValueError):
                analyze_records(*raw)

    def test_manifest_and_summary_receipt_are_required(self):
        raw = deepcopy(self.raw)
        raw[1]["splits"]["train"]["states"] -= 16
        raw[1]["splits"]["validation"]["states"] += 16
        result = analyze_records(*raw)
        self.assertFalse(result["coverage"]["data_manifest_complete"])
        self.assertEqual(result["coverage"]["status"], "INCOMPLETE")
        raw = deepcopy(self.raw)
        raw[5][0]["recorded_states"] -= 1
        with self.assertRaises(ValueError):
            analyze_records(*raw)

    def test_diagnostic_uses_three_reused_worlds_with_error_denominator(self):
        rows = self.complete["diagnostic_summary"]
        lora = next(r for r in rows if r["method"] == "LoRA")
        self.assertEqual((lora["requested_reused_worlds"], lora["certified_outputs"], lora["wrong_certified_outputs"]), (3, 3, 1))
        base = next(r for r in rows if r["method"] == "BaseQwen")
        self.assertEqual((base["cap_abstentions"], base["all_abstentions_including_failures"]), (3, 3))
        self.assertEqual(self.complete["computational_costs"]["diagnostic_extra_unique_reference_observations"], 0)

    def test_costs_use_paths_once_and_do_not_add_load_twice(self):
        costs = self.complete["computational_costs"]
        self.assertEqual(costs["sum_stage_wall_seconds"], 33.)
        self.assertTrue(costs["end_to_end_receipts_available"])
        lora = next(r for r in costs["methods"] if r["method"] == "LoRA")
        self.assertEqual(lora["recorded_path_calls"], 24 * 4 + 3 * 2)
        self.assertEqual(lora["recorded_calls"], 120 + 24 * 4 + 3 * 2)
        self.assertEqual(lora["costs_observed_sum"]["task"] + lora["costs_observed_sum"]["type"], 24 * 512 + 3 * 256)
        self.assertEqual(lora["call_latency_observed"], lora["recorded_calls"])
        self.assertEqual(costs["charged_unrecorded_qwen_calls"], 0)
        raw = deepcopy(self.raw)
        raw[4]["evaluation"]["resident_model"] = {}
        self.assertFalse(analyze_records(*raw)["computational_costs"]["end_to_end_receipts_available"])
        raw[4]["evaluation"]["policy_calls"]["calls"] -= 1
        with self.assertRaises(ValueError):
            analyze_records(*raw)

    def test_unrecorded_or_over_budget_qwen_calls_prevent_complete(self):
        for charged in (self.raw[4]["evaluation"]["policy_calls"]["calls"] + 1, 601):
            raw = deepcopy(self.raw)
            raw[4]["evaluation"]["policy_calls"]["calls"] = charged
            result = analyze_records(*raw)
            self.assertEqual(result["coverage"]["status"], "INCOMPLETE")
            self.assertFalse(result["coverage"]["qwen_calls_fully_accounted_within_600"])

    def test_diagnostic_certification_requires_terminal_interval_and_same_candidate(self):
        for malformed in ("candidate", "endpoint", "gate_history", "uncertified", "early_abstain"):
            raw = deepcopy(self.raw)
            row = next(r for r in raw[3] if r["method"] == ("BaseQwen" if malformed == "early_abstain" else "LoRA")
                       and r["mode"] == "fixed_confidence_diagnostic")
            if malformed == "candidate":
                row["strictly_certified_output"] = [1, 1, 1, 1]
            elif malformed == "endpoint":
                row["snapshots"][-1]["strict_certificate"]["gap_lower"] = "2"
            elif malformed == "gate_history":
                row["gate_history"] = []
            elif malformed == "uncertified":
                row["complete"] = False
                row["abstained"] = True
            else:
                row["online"] = 512
            with self.subTest(malformed=malformed), self.assertRaises(ValueError):
                analyze_records(*raw)

    def test_no_model_outputs_produces_incomplete_report_without_figures(self):
        result = analyze_records({}, {}, [], [], {}, None)
        self.assertEqual(result["coverage"]["status"], "INCOMPLETE")
        self.assertEqual(len(result["coverage"]["offline"]["missing"]), 360)
        self.assertEqual(len(result["coverage"]["paths"]["missing"]), 189)
        self.assertTrue(all(r["exact_recovery"] is None for r in result["primary_summary"]))
        self.assertEqual(result["computational_costs"]["primary_recorded_world_unique_reference_observations"], 0)
        with TemporaryDirectory() as directory:
            write_reports(result, directory)
            self.assertEqual(plots(result, directory), [])
            self.assertIn("incomplete coverage", (Path(directory) / "QUERY_POLICY_EVALUATION.md").read_text())
            self.assertEqual(len(list(Path(directory).iterdir())), 2)

    def test_complete_report_and_json_are_finite_and_explicit(self):
        json.dumps(self.complete, allow_nan=False)
        with TemporaryDirectory() as directory:
            write_reports(self.complete, directory)
            report = (Path(directory) / "QUERY_POLICY_EVALUATION.md").read_text()
            self.assertIn("teacher_percent", report)
            self.assertIn("n=8", report)
            self.assertIn("固定预算猜测", report)
            costs = (Path(directory) / "COMPUTATIONAL_COST.md").read_text()
            self.assertIn("未重复相加两次", costs)


if __name__ == "__main__":
    unittest.main()
